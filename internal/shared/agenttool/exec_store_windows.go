//go:build windows

package agenttool

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"unsafe"

	"golang.org/x/sys/windows"
)

type windowsExecTrust struct{}

var windowsRootStoreName = [...]uint16{'R', 'o', 'o', 't', 0}

func userTrustStore() execTrustStore { return windowsExecTrust{} }

func (windowsExecTrust) trusted(_ context.Context, a *execAuthority) (bool, error) {
	return withWindowsRoot(a, windows.CERT_STORE_READONLY_FLAG, func(*windows.CertContext) error { return nil })
}

func (windowsExecTrust) install(ctx context.Context, path string) error {
	system, err := windows.GetSystemDirectory()
	if err != nil {
		return err
	}
	//nolint:gosec // Only the system's certutil, with a certificate generated by this process.
	output, err := exec.CommandContext(ctx, filepath.Join(system, "certutil.exe"),
		"-user", "-addstore", "Root", path).CombinedOutput()
	if err != nil {
		return fmt.Errorf("certutil: %w: %s", err, output)
	}
	return nil
}

func (windowsExecTrust) remove(_ context.Context, a *execAuthority) error {
	_, err := withWindowsRoot(a, 0, func(cert *windows.CertContext) error {
		return windows.CertDeleteCertificateFromStore(windows.CertDuplicateCertificateContext(cert))
	})
	return err
}

func withWindowsRoot(a *execAuthority, flags uint32, use func(*windows.CertContext) error) (bool, error) {
	//nolint:gosec // CertOpenStore takes a provider-specific pointer to the UTF-16 store name.
	store, err := windows.CertOpenStore(windows.CERT_STORE_PROV_SYSTEM_REGISTRY, 0, 0,
		windows.CERT_SYSTEM_STORE_CURRENT_USER|windows.CERT_STORE_OPEN_EXISTING_FLAG|flags,
		uintptr(unsafe.Pointer(&windowsRootStoreName[0])))
	if errors.Is(err, windows.ERROR_FILE_NOT_FOUND) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	defer windows.CertCloseStore(store, 0) //nolint:errcheck // Only the operation's result matters.

	var prev *windows.CertContext
	for {
		cert, err := windows.CertEnumCertificatesInStore(store, prev)
		if errors.Is(err, windows.Errno(windows.CRYPT_E_NOT_FOUND)) {
			return false, nil
		}
		if err != nil {
			return false, err
		}
		der := unsafe.Slice(cert.EncodedCert, cert.Length) //nolint:gosec // Owned by the live Windows cert context.
		if bytes.Equal(a.root.Raw, der) {
			defer windows.CertFreeCertificateContext(cert) //nolint:errcheck // The enumeration ends at this certificate.

			return true, use(cert)
		}

		prev = cert
	}
}

func privateExecDir(path string, create bool) error {
	user, err := windows.GetCurrentProcessToken().GetTokenUser()
	if err != nil {
		return err
	}
	name, err := windows.UTF16PtrFromString(path)
	if err != nil {
		return err
	}
	if create {
		if err := createWindowsExecDir(name, user.User.Sid); err != nil && !errors.Is(err, windows.ERROR_ALREADY_EXISTS) {
			return err
		}
	}
	attrs, err := windows.GetFileAttributes(name)
	if err != nil {
		return err
	}
	if attrs&windows.FILE_ATTRIBUTE_REPARSE_POINT != 0 || attrs&windows.FILE_ATTRIBUTE_DIRECTORY == 0 {
		return errors.New("exec-ca must be a private directory, not a reparse point")
	}

	return checkWindowsExecDir(path, user.User.Sid)
}

func createWindowsExecDir(name *uint16, sid *windows.SID) error {
	sd, err := windows.SecurityDescriptorFromString("O:" + sid.String() + "D:P(A;OICI;FA;;;" + sid.String() + ")")
	if err != nil {
		return err
	}
	var attrs windows.SecurityAttributes
	attrs.Length = uint32(unsafe.Sizeof(attrs))
	attrs.SecurityDescriptor = sd

	return windows.CreateDirectory(name, &attrs)
}

func checkWindowsExecDir(path string, sid *windows.SID) error {
	sd, err := windows.GetNamedSecurityInfo(path, windows.SE_FILE_OBJECT,
		windows.OWNER_SECURITY_INFORMATION|windows.DACL_SECURITY_INFORMATION)
	if err != nil {
		return err
	}
	owner, _, err := sd.Owner()
	if err != nil {
		return err
	}
	acl, _, err := sd.DACL()
	if err != nil {
		return err
	}
	control, _, err := sd.Control()
	if err != nil {
		return err
	}
	if !sid.Equals(owner) || acl == nil || acl.AceCount != 1 || control&windows.SE_DACL_PROTECTED == 0 {
		return errors.New("exec-ca must be accessible only to the current user")
	}
	var ace *windows.ACCESS_ALLOWED_ACE
	if err := windows.GetAce(acl, 0, &ace); err != nil {
		return err
	}
	const inherit = windows.OBJECT_INHERIT_ACE | windows.CONTAINER_INHERIT_ACE
	//nolint:gosec // A Windows access-allowed ACE stores the variable-length SID at SidStart.
	if ace.Header.AceType != windows.ACCESS_ALLOWED_ACE_TYPE || ace.Header.AceFlags != inherit ||
		!sid.Equals((*windows.SID)(unsafe.Pointer(&ace.SidStart))) {
		return errors.New("exec-ca and its files must be accessible only to the current user")
	}

	return nil
}

func lockExecFile(f *os.File) error {
	return windows.LockFileEx(windows.Handle(f.Fd()), windows.LOCKFILE_EXCLUSIVE_LOCK|windows.LOCKFILE_FAIL_IMMEDIATELY,
		0, 1, 0, &windows.Overlapped{})
}
