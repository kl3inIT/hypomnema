// Writes .orca/types into this plugin from a clone of Orca's source, as `orca plugin types` does
// (src/cli/plugin-authoring/plugin-type-files.ts at Orca v1.4.248, writePluginTypeFiles): for an Orca whose
// package lacks resources/plugins/declarative/orca.d.ts, where `orca plugin types` fails with ENOENT.
// Usage: node tools/types-from-source.mjs <orca clone> [plugin folder, default: this plugin]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const [source, target = join(dirname(fileURLToPath(import.meta.url)), '..')] = process.argv.slice(2)
if (!source) {
  console.error('usage: node tools/types-from-source.mjs <orca clone> [plugin folder]')
  process.exit(2)
}

const plugins = join(resolve(source), 'resources', 'plugins')
const surfaces = ['orca-host', 'orca-frame', 'orca-worker', 'orca-services', 'orca-testing']
const note =
  '// Written by `orca plugin types`; regenerated by `orca plugin dev load`. Do not edit.\n'
const typings = {
  orca: [
    'orca.d.ts',
    'orca-components.d.ts',
    'orca-components-layout.d.ts',
    'orca-components-data.d.ts'
  ]
    .map((file) => readFileSync(join(plugins, 'declarative', file), 'utf8'))
    .join('\n')
}
for (const dir of surfaces)
  typings[dir] = readFileSync(join(plugins, 'types', `${dir}.d.ts`), 'utf8')

const types = join(resolve(target), '.orca', 'types')
for (const [dir, text] of Object.entries(typings)) {
  mkdirSync(join(types, dir), { recursive: true })
  writeFileSync(join(types, dir, 'index.d.ts'), note + text)
}
writeFileSync(join(types, '..', '.gitignore'), '*\n')
const compilerOptions = {
  strict: true,
  noEmit: true,
  target: 'ES2022',
  module: 'ESNext',
  moduleResolution: 'Bundler',
  allowImportingTsExtensions: true,
  isolatedModules: true,
  jsx: 'react-jsx',
  jsxImportSource: 'orca',
  lib: ['ES2022', 'DOM'],
  preserveSymlinks: true,
  typeRoots: ['.'],
  types: ['orca', ...surfaces]
}
writeFileSync(join(types, 'tsconfig.json'), `${JSON.stringify({ compilerOptions }, null, 2)}\n`)
console.log(`wrote ${types}`)
